const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const chain=JSON.parse(fs.readFileSync(root+'/chain/chain.json','utf8'));
const blocks=chain.blocks.slice(0,150).map(b=>[b.height,b.hash,b.burnBlockHeight,b.time]);
const tw=JSON.parse(fs.readFileSync(root+'/art/twins-webp/manifest.json','utf8'));
const art=[],counts={},sources={generated:new Date().toISOString(),twins:[],nftCandidates:{},chain:{source:chain.source,fetchedAt:chain.fetchedAt,blocks:blocks.length,note:'Stacks blocks 1-150 from the Hiro API via xtrata.xyz/hiro proxy'},logosNeedingPermission:[],imagesNotFound:[]};
for(const [slug,c] of Object.entries(tw.collections)){
  counts[slug]=c.inscribed;
  for(const t of c.tokens){
    const b=fs.readFileSync(path.join(root,'art/twins-webp',t.file));
    art.push({key:slug,tokenId:t.tokenId,xtrataId:t.xtrataId,src:'data:image/webp;base64,'+b.toString('base64')});
    sources.twins.push({collection:c.name,tokenId:t.tokenId,xtrataId:t.xtrataId,file:t.file,format:t.webp,originalFile:t.originalFile,originalSha256:t.originalSha256,originalBytes:t.originalBytes,sourceUrl:t.sourceUrl,srcSize:t.srcSize});
  }
}
const nft={};
for(const slug of ['arties','satoshe','satoshibles','stacks-punks','this-is-1','boomboxes']){
  const m=JSON.parse(fs.readFileSync(root+`/art/${slug}/manifest.json`,'utf8'));
  nft[slug]={contract:m.contract,tokens:m.candidateTokens.map(t=>({id:t.tokenId,img:t.imageUrl||null,hiro:t.hiroCachedImage||null,uri:t.tokenUri||null}))};
  sources.nftCandidates[slug]={contract:m.contract,verifiedOnChain:m.verifiedOnChain,tokens:m.candidateTokens.length};
  sources.imagesNotFound.push({collection:m.collection,contract:m.contract,reason:'image/metadata hosts blocked from the build sandbox; resolved live in the browser at runtime, placeholder tile until then'});
}
const stops=JSON.parse(fs.readFileSync(root+'/gen/test-stops.json','utf8'));
const js='/* Genesis 21 art + data bundle (generated by build/bundle_art.cjs) */\n'+
 'window.G21_CHAIN='+JSON.stringify({blocks})+';\n'+
 'window.G21_NFT='+JSON.stringify(nft)+';\n'+
 'window.G21_TWINS='+JSON.stringify(counts)+';\n'+
 'window.G21_ART='+JSON.stringify(art)+';\n'+
 'window.G21_TEST_STOPS='+JSON.stringify(stops)+';\n';
fs.writeFileSync(root+'/gen/art.js',js);
fs.writeFileSync(root+'/sources.json',JSON.stringify(sources,null,1));
console.log('art.js',js.length,'bytes; twins',art.length,'blocks',blocks.length);
