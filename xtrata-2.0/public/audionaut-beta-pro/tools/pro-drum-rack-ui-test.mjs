import assert from 'node:assert/strict';
import { serve, browser, page } from './serve.mjs';
const { srv, url } = await serve(), b = await browser(), logs = [];
let checks = 0;
const ok = (value, message) => { assert.ok(value, message); checks++; };
try {
  const p = await page(b, url, { logs });
  await p.goto(url + '/audionaut-beta-pro/daw.html');
  await p.waitForSelector('#pro-workspace-nav');
  await p.evaluate(async () => {
    const base = '/audionaut-beta-pro/daw/js/';
    const { store, makeProject } = await import(base + 'state.js');
    store.loadProject(makeProject());
    const track = store.addInstrument('drumrack'); store.setTrackProp(track.id, 'name', 'Test rack');
    window.drumTest = { store, track, engine: (await import(base + 'engine.js')).engine };
    (await import(base + 'synth-panel.js')).openSynthPanel(store.project.instruments.indexOf(track));
    const pitches = []; document.addEventListener('synth-note', ({ detail }) => { if (detail.on) pitches.push(detail.pitch); });
    drumTest.pitches = pitches;
  });
  ok((await p.locator('#sfp-oct-lbl').textContent()).includes('C1 · MIDI 36'), 'Drum keyboard defaults to C1 / MIDI 36');
  ok(await p.locator('#sfp-keys .sfp-key').count() === 16, 'All 16 mapped pads have keys, without extra silent octaves');
  const geometry = await p.locator('#sfp-keys').evaluate(el => {
    const bounds = el.getBoundingClientRect(); return [...el.querySelectorAll('.sfp-key')].every(k => { const r = k.getBoundingClientRect(); return r.left >= bounds.left - 1 && r.right <= bounds.right + 1; });
  });
  ok(geometry, 'Partial-octave black keys fit the shared keyboard');
  const knobs = await p.locator('.sfp-drumrack .knob-wrap').evaluateAll(nodes => nodes.map(n => n.getBoundingClientRect().top));
  ok(knobs.length === 4 && Math.max(...knobs) - Math.min(...knobs) < 2, 'All four knobs sit side by side');
  await p.evaluate(async () => {
    const ctx = drumTest.engine.ensureContext(); await ctx.resume();
    const analyser = ctx.createAnalyser(), silent = ctx.createGain(); silent.gain.value = 0;
    drumTest.engine.masterGain.connect(analyser); analyser.connect(silent).connect(ctx.destination);
    const data = new Float32Array(analyser.fftSize); drumTest.peak = 0;
    drumTest.timer = setInterval(() => { analyser.getFloatTimeDomainData(data); for (const x of data) drumTest.peak = Math.max(drumTest.peak, Math.abs(x)); }, 5);
  });
  await p.locator('#sfp-keys [data-midi="36"]').click({ position: { x: 5, y: 60 } });
  await p.waitForFunction(() => drumTest.peak > .01, null, { timeout: 5000 });
  ok(await p.evaluate(() => drumTest.peak > .01), 'Clicking the C1 kick produces real audio');
  await p.keyboard.press('a'); await p.waitForTimeout(80);
  ok(await p.evaluate(() => drumTest.pitches.filter(n => n === 36).length >= 2), 'Computer keyboard and on-screen keyboard trigger the same kick');
  await p.keyboard.press('x');
  ok((await p.locator('#sfp-oct-lbl').textContent()).includes('C1'), 'Drum keys stay on their playable range');
  await p.getByRole('button', { name: 'Browse drum samples', exact: true }).click();
  await p.locator('#modal-loader:not(.hidden)').waitFor();
  ok(await p.locator('#modal-loader').isVisible(), 'Drum panel opens the shared library');
  ok((await p.locator('#library-category option:checked').textContent()).includes('Analog'), 'Browser opens the drum pack');
  await p.locator('#loader-cancel').click();
  ok(await p.evaluate(() => !drumTest.track.sampleInstrument), 'Cancelling leaves starter mappings unchanged');
  await p.getByRole('button', { name: 'Browse drum samples', exact: true }).click();
  await p.locator('#modal-loader:not(.hidden)').waitFor();
  await p.locator('#loader-load').click();
  await p.waitForFunction(() => drumTest.track.sampleInstrument?.pads[0].sourceId, null, { timeout: 60000 });
  const assigned = await p.evaluate(async () => {
    const { store, track, engine } = drumTest, config = track.sampleInstrument;
    const entry = config.sources.find(s => s.id === config.pads[0].sourceId), channel = store.track(entry.sourceTrackId);
    const { exportProjectAsync, importProject } = await import('/audionaut-beta-pro/daw/js/persistence.js');
    const decodedBefore = !!engine.buffers[store.project.channels.indexOf(channel)];
    const history = await import('/audionaut-beta-pro/daw/js/history.js');
    history.undo();
    const undoClean = !store.track(track.id).sampleInstrument?.pads[0].sourceId && !store.track(channel.id);
    history.redo();
    const redoMapped = store.track(track.id).sampleInstrument.pads[0].sourceId === config.pads[0].sourceId && !!store.track(channel.id);
    const restored = importProject(await exportProjectAsync());
    await (await import('/audionaut-beta-pro/daw/js/loader.js')).reloadAllSamples();
    const rack = restored.instruments.find(t => t.id === track.id); drumTest.track = rack;
    return { undoClean, redoMapped, type: channel.source.type, value: channel.source.value, decoded: decodedBefore && !!engine.buffers[store.project.channels.findIndex(c => c.id === channel.id)], mapped: rack.sampleInstrument.pads[0].sourceId === config.pads[0].sourceId, unassigned: config.pads.slice(1).every(p => !p.sourceId), originalChannels: store.project.channels.slice(0, 4).every(c => !c.source) };
  });
  ok(assigned.type === 'pack' && assigned.value.startsWith('analogkit/'), 'Assignment retains the existing pack source reference');
  ok(assigned.undoClean && assigned.redoMapped, 'Pad assignment and its sample channel undo/redo together');
  ok(assigned.decoded, 'Shared loader decodes the actual library sample');
  ok(assigned.mapped && assigned.unassigned && assigned.originalChannels, 'Save/reload retains pad mapping without replacing other sounds');
  await p.evaluate(() => { drumTest.peak = 0; });
  await p.getByRole('button', { name: 'Play pad', exact: true }).click();
  await p.waitForFunction(() => drumTest.peak > .001, null, { timeout: 5000 });
  ok(await p.evaluate(() => drumTest.peak > .001), 'Loaded library pad produces real audio');
  await p.getByRole('tab', { name: 'New instruments', exact: true }).click();
  await p.getByText('Edit pad samples and controls', { exact: true }).click();
  await p.getByRole('button', { name: 'Browse samples for Snare', exact: true }).click();
  await p.locator('#modal-loader:not(.hidden)').waitFor();
  ok((await p.locator('#loader-channel-label').textContent()).includes('Snare'), 'Pad editor targets the selected drum');
  await p.locator('#loader-cancel').click();
  await p.evaluate(async () => { (await import('/audionaut-beta-pro/daw/js/synth-panel.js')).openSynthPanel(drumTest.store.project.instruments.indexOf(drumTest.track)); });
  await p.setViewportSize({ width: 390, height: 844 });
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), 'Panel fits a phone viewport');
  await p.screenshot({ path: `/tmp/audionaut-drum-rack-${process.env.AUDIONAUT_TEST_BROWSER || 'chromium'}-mobile.png`, fullPage: true });
  await p.setViewportSize({ width: 1400, height: 900 });
  await p.locator('#synth-front').screenshot({ path: `/tmp/audionaut-drum-rack-${process.env.AUDIONAUT_TEST_BROWSER || 'chromium'}.png` });
  const retained = await p.evaluate(() => JSON.stringify(drumTest.store.project));
  await p.getByRole('button', { name: 'Browse drum samples', exact: true }).click();
  await p.locator('#modal-loader:not(.hidden)').waitFor();
  await p.locator('#modal-loader [data-tab="url"]').click();
  await p.locator('#input-url').fill(url + '/missing-drum.wav');
  await p.locator('#loader-load').click();
  await p.waitForFunction(() => document.querySelector('#status-text').textContent.startsWith('Load failed:'));
  ok(await p.evaluate(before => JSON.stringify(drumTest.store.project) === before, retained), 'Failed sample loading preserves the previous pad and song');
  await p.getByRole('button', { name: 'Browse drum samples', exact: true }).click();
  await p.locator('#modal-loader:not(.hidden)').waitFor();
  await p.evaluate(async () => { const {makeProject} = await import('/audionaut-beta-pro/daw/js/state.js'); drumTest.store.loadProject(makeProject()); });
  const fresh = await p.evaluate(() => JSON.stringify(drumTest.store.project));
  await p.locator('#loader-load').click();
  await p.waitForFunction(() => document.querySelector('#status-text').textContent.startsWith('Load failed:'));
  ok(await p.evaluate(before => JSON.stringify(drumTest.store.project) === before, fresh), 'A stale picker cannot assign samples into a different project');
  await p.evaluate(() => clearInterval(drumTest.timer));
  ok(!logs.some(x => /pageerror:/.test(x)), logs.join('\n'));
  console.log(JSON.stringify({ checks, browser: process.env.AUDIONAUT_TEST_BROWSER || 'chromium', assigned }));
} catch (error) {
  for (const context of b.contexts()) for (const p of context.pages()) console.error(await p.evaluate(() => ({ peak: window.drumTest?.peak, pitches: window.drumTest?.pitches, state: window.drumTest?.engine.ctx?.state, time: window.drumTest?.engine.ctx?.currentTime, error: window.drumTest?.engine.lastVoiceError })).catch(() => ({})));
  throw error;
} finally { await b.close(); srv.close(); }
