#!/usr/bin/env python3
"""Build the preservation-checker dataset from the census.

    python3 -I export_checker_data.py [--frozen frozen-flags.json] [--out out/checker-data.json]

Inputs (all read-only):
  ../census/ft-census-results-classified.csv   one row per collection with its census bucket and evidence
  ../census/ft-census-results.json             raw run (per-collection date, contract-source signals)
  checker-verdicts.json                        hand-checked layer (summaries, status overrides, helper hints, 16 Oct re-test)
  --frozen                                     optional output of ft-frozen-flags.js (the metadata-frozen flag read from chain)

Output: one record per collection, keyed by contract id, on ONE public scale (see SCALE). Records carry the date and the kind
of evidence, plus plain-English "good" and "worry" lines generated by fixed rules, so nobody hand-writes 241 verdicts.
There is no rank and no volume in the output on purpose: the page answers "what about the thing I hold", it is not a league table.

The script also checks its own output against the numbers in the census write-up and stops if they disagree.
"""
import argparse
import csv
import datetime
import json
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
CENSUS = HERE.parent / 'census'

# The one public scale. Census buckets and the older risk ratings (Lost / High / Medium / Lower) both fold into this.
SCALE = {
    'on_chain':           {'order': 0, 'label': 'Stored on chain'},
    'solid':              {'order': 1, 'label': 'Looks solid'},
    'one_host':           {'order': 2, 'label': 'Works today, rests on one host'},
    'marketplace_broken': {'order': 3, 'label': 'Contract works, marketplace copy broken'},
    'marketplace_only':   {'order': 4, 'label': "Only the marketplace's copy still works"},
    'not_found':          {'order': 5, 'label': "We couldn't find the art"},
    'unclear':            {'order': 6, 'label': "We couldn't tell"},
    'not_art':            {'order': 7, 'label': 'Not an art collection'},
}
BUCKET_STATUS = {
    'On chain': 'on_chain',
    'Healthy': 'solid',
    'Fragile': 'one_host',
    'Marketplace copy broken': 'marketplace_broken',
    'Walking dead': 'marketplace_only',
    'Failing': 'not_found',
    'Lost': 'not_found',
    'Unclear': 'unclear',
    'Not artwork': 'not_art',
}
BROKEN_BUCKETS = {'Walking dead', 'Failing', 'Lost'}  # the census's "34 that no longer reach their art through their own contract"
CONTRACT_REACHES = {'works': True, 'works-template': True, 'shared-file': False, 'dead': False, 'uri-error': False, 'no-image-field': False, 'unverified': None}
HOSTS = {'several hosts': 'several', 'Pinata only': 'pinata_only', 'not found on IPFS': 'none', '': None}
ART_HOST = {'IPFS': 'ipfs', 'Own server / API': 'own_server', 'Arweave': 'arweave', 'AWS S3': 'cloud_bucket', 'Other': 'other', '': None}

CAVEATS = [
    'Sample-based: up to 4 tokens per collection through the contract and up to 16 through the marketplace image address.',
    'One run on 13 Oct 2026 from one network; the collections that no longer reach their art through their contract were re-tested on 16 Oct 2026.',
    "'Risk' here means the art or its metadata may stop being retrievable or may change. It does not mean custody, price or security of the tokens.",
    "'Only Pinata answered' shows who holds the files today, not how long they will keep them.",
    "'Has a setter' means a function for changing the token link was found by its usual name. It does not show the owner can still use it: the frozen flag is read separately.",
]


def fail(msg):
    print('EXPORT FAILED: ' + msg, file=sys.stderr)
    sys.exit(1)


def ratio(text):
    """'16/16' -> (16, 16); anything else -> (None, None)."""
    try:
        a, b = str(text).split('/')
        return int(a), int(b)
    except ValueError:
        return None, None


def to_int(text):
    try:
        return int(str(text).replace(',', ''))
    except ValueError:
        return None


def pretty_date(iso):
    """'2026-10-13' -> '13 Oct 2026'"""
    d = datetime.date.fromisoformat(iso)
    return f'{d.day} {d.strftime("%b %Y")}'


def build_lines(rec):
    """Plain-English good / worry lines from fixed rules. Each line states only what the fields support."""
    good, worry = [], []
    status, contract, market, art, owner = rec['status'], rec['contract'], rec['marketplace'], rec['art'], rec['owner']
    if status == 'not_art':
        return good, worry
    broken = status in ('marketplace_only', 'not_found')

    if status == 'on_chain':
        good.append("The contract can rebuild the image on chain, so the picture itself doesn't depend on an outside file.")
        if rec.get('_uri_storage') == 'IPFS':
            worry.append('The standard token link still points to a file on IPFS.')
    if contract['reaches_art'] is True:
        good.append("The contract's own link still reaches the art.")
    elif contract['reaches_art'] is False:
        worry.append("The contract's own link no longer reaches the art.")
    else:
        worry.append("We couldn't read this contract's token link, so we can't say whether the art can be reached from it.")

    loaded, sampled = market['loaded'], market['sampled']
    if sampled:
        if loaded == sampled:
            good.append(f'Marketplace images loaded for all {sampled} sampled pieces.')
        elif loaded == 0:
            worry.append(f'None of the {sampled} sampled marketplace images loaded.')
        else:
            worry.append(f'Marketplace images loaded for only {loaded} of {sampled} sampled pieces.')
    if status == 'marketplace_only':
        worry.append('What the marketplace shows comes from its own copy of the art, not from the contract.')
        if market['single_pinata_account']:
            worry.append("The marketplace's copy is served from a single Pinata account.")

    if status == 'on_chain':
        pass  # the picture is rebuilt on chain; the IPFS measurement describes the metadata file, not the art
    elif art['hosts'] == 'several':
        good.append('When we tested, several independent hosts held the art on IPFS.')
    elif art['hosts'] == 'pinata_only':
        worry.append("When we tested, only Pinata held the art on the IPFS network. That shows who holds it today, not how long they will.")
    elif art['hosts'] == 'none':
        worry.append("We couldn't find the art on the IPFS network.")
    if art['storage'] == 'arweave':
        good.append('The art is on Arweave, which is built for permanent storage.')
    elif art['storage'] == 'own_server' and contract['reaches_art'] is True:
        worry.append("The art is served from the project's own server.")
    elif art['storage'] == 'cloud_bucket' and contract['reaches_art'] is True:
        worry.append('The art sits in a cloud storage bucket.')

    if owner['has_uri_setter']:
        if owner['frozen'] is True:
            good.append('The owner has locked the token link for good.')
            if broken:
                worry.append("Because the link is locked, a dead link can't be repaired by changing it.")
        elif owner['frozen'] is False:
            if broken:
                good.append('Because the owner can still change the link, a dead link could be repaired.')
            else:
                worry.append('The owner can still change where the token link points.')
        else:
            state = owner['frozen_state']
            if state == 'no_flag':
                unknown = "we couldn't find a flag that shows whether it has been locked."
            elif state == 'read_failed':
                unknown = "we couldn't read whether it has been locked."
            else:
                unknown = "we haven't yet checked whether it has been locked."
            if broken:
                good.append(f'The contract has a function for changing the token link, so the dead link may be repairable; {unknown}')
            else:
                worry.append(f'The contract has a function for changing the token link, and {unknown}')
                if not owner['freeze_mentioned']:
                    worry.append("We didn't find a way to lock it, so the link may stay changeable.")
    else:
        good.append("We didn't find a function for changing the token link.")

    helper = rec.get('helper')
    if helper and helper.get('state') == 'live':
        if helper.get('twins') and helper.get('of') and helper['twins'] >= helper['of']:
            good.append(f"Every piece in this collection already has a permanent on-chain twin (as of {pretty_date(helper['as_of'])}).")
        else:
            good.append('A Forever Twins helper is live for this collection, so a piece can be given a permanent on-chain twin.')
    return good, worry


def headline(rec):
    status, market = rec['status'], rec['marketplace']
    if status == 'not_found':
        if market['sampled'] and market['loaded']:
            return f"We could find the art for only {market['loaded']} of {market['sampled']} sampled pieces."
        return "We couldn't find the art. The contract's link is dead and no marketplace copy loaded."
    return {
        'on_chain': 'The art can be rebuilt from the contract itself.',
        'solid': 'The contract reaches the art and several independent hosts hold it.',
        'one_host': 'The contract reaches the art today, but it rests on a single host or server.',
        'marketplace_broken': "The contract still reaches the art, but the marketplace's copy is partly broken.",
        'marketplace_only': "The contract's link no longer reaches the art. It shows only because the marketplace kept a copy.",
        'unclear': "We couldn't verify this one.",
        'not_art': "This isn't an art collection, so there is no art to preserve here.",
    }[status]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--frozen', help='JSON written by ft-frozen-flags.js (FTFROZEN.download())')
    ap.add_argument('--out', default=str(HERE / 'out' / 'checker-data.json'))
    args = ap.parse_args()

    rows = list(csv.DictReader(open(CENSUS / 'ft-census-results-classified.csv', encoding='utf-8')))
    raw = json.load(open(CENSUS / 'ft-census-results.json', encoding='utf-8'))
    overrides = json.load(open(CENSUS / 'manual-overrides.json', encoding='utf-8'))
    verdicts = json.load(open(HERE / 'checker-verdicts.json', encoding='utf-8'))
    hand = verdicts['collections']
    retest = verdicts['retest']
    frozen = {}
    if args.frozen:
        frozen = json.load(open(args.frozen, encoding='utf-8'))
        frozen = frozen.get('results', frozen)

    by_id = {}
    for r in rows:
        if r['id'] in by_id:
            fail('duplicate contract id in census: ' + r['id'])
        by_id[r['id']] = r
    for cid, v in hand.items():
        if cid not in by_id:
            fail(f"verdict for a contract that is not in the census: {cid}")
        if v['name'] != by_id[cid]['name']:
            fail(f"verdict name {v['name']!r} does not match census name {by_id[cid]['name']!r} for {cid}")
    for cid in retest['marketplace_overrides']:
        if cid not in by_id:
            fail('re-test override for a contract that is not in the census: ' + cid)

    collections = {}
    for cid, r in sorted(by_id.items()):
        bucket = r['bucket']
        v = hand.get(cid, {})
        raw_row = raw['results'].get(cid, {})
        src = raw_row.get('src') or {}
        census_day = (raw_row.get('at') or '')[:10] or None
        retested = bucket in BROKEN_BUCKETS

        loaded, sampled = ratio(r['marketplace_ok'])
        market_day = census_day
        if cid in retest['marketplace_overrides']:
            loaded, sampled = retest['marketplace_overrides'][cid]['loaded'], retest['marketplace_overrides'][cid]['sampled']
            market_day = retest['date']

        status = v.get('status', BUCKET_STATUS[bucket])
        f = frozen.get(cid) or {}
        fstate = f.get('state')
        frozen_value = True if fstate == 'frozen' else False if fstate == 'not_frozen' else None

        rec = {
            'id': cid,
            'name': r['name'],
            'chain': 'stacks',
            'tokens_approx': to_int(r['last_token_id']),
            'deployed': r['deployed'] or None,
            'status': status,
            'census_bucket': bucket,
            'headline': None,
            'summary': v.get('summary'),
            'evidence_level': 'hand_checked' if (cid in overrides or 'evidence' in v) else 'sampled',
            'evidence': v.get('evidence'),
            'checked': {'contract': retest['date'] if retested else census_day, 'marketplace': market_day},
            'contract': {'reaches_art': CONTRACT_REACHES[r['contract_state']], 'state': r['contract_state']},
            'marketplace': {
                'loaded': loaded, 'sampled': sampled, 'state': r['marketplace_state'], 'host': r['marketplace_host'] or None,
                'single_pinata_account': r['gamma_pinata'] == 'True',
            },
            'art': {'storage': ART_HOST.get(r['art_storage'], 'none_per_token' if r['art_storage'].startswith('None per token') else None),
                    'hosts': HOSTS[r['ipfs_durability']]},
            'owner': {
                'has_uri_setter': r['uri_changeable'] == 'True',
                'freeze_mentioned': bool(src.get('freezeFn')),
                'frozen': frozen_value,
                'frozen_state': fstate,
                'frozen_read_at': f.get('at'),
            },
            'facts': [r['notes']] if r['notes'] else [],
            'helper': v.get('helper'),
            '_uri_storage': r['uri_storage'],
        }
        rec['headline'] = v.get('headline') or headline(rec)
        rec['good'], rec['worry'] = build_lines(rec)
        del rec['_uri_storage']
        collections[cid] = rec

    # ---- Checks against the census write-up (stop rather than ship numbers that disagree with it) ----
    art = [c for c in collections.values() if c['status'] != 'not_art']
    broken = [c for c in collections.values() if c['census_bucket'] in BROKEN_BUCKETS]
    expect = {
        'collections in census': (len(collections), 250),
        'art collections': (len(art), 241),
        'broken through their own contract': (len(broken), 34),
        'art collections with a setter for the token link': (sum(c['owner']['has_uri_setter'] for c in art), 177),
        'broken ones with a setter': (sum(c['owner']['has_uri_setter'] for c in broken), 25),
        'Healthy': (sum(c['census_bucket'] == 'Healthy' for c in collections.values()), 26),
        'Fragile': (sum(c['census_bucket'] == 'Fragile' for c in collections.values()), 173),
    }
    bad = [f'{k}: got {got}, the census write-up says {want}' for k, (got, want) in expect.items() if got != want]
    if bad:
        fail('numbers disagree with the census write-up:\n  ' + '\n  '.join(bad))
    for c in collections.values():
        if c['status'] in ('marketplace_only', 'not_found') and c['contract']['reaches_art'] is not False:
            fail(f"{c['id']} is marked {c['status']} but its contract link is not recorded as broken")
        if c['status'] not in SCALE:
            fail(f"{c['id']} has an unknown status {c['status']!r}")

    counts = Counter(c['status'] for c in collections.values())
    out = {
        'schema': 1,
        'generated': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'scale': SCALE,
        'caveats': CAVEATS,
        'sources': {
            'census': {'date': '2026-10-13', 'harness': raw.get('harness'), 'collections': len(collections)},
            'retest': {'date': retest['date'], 'scope': retest['scope']},
            'frozen_flags': {'read': bool(frozen), 'collections': len(frozen)},
        },
        'counts': dict(sorted(counts.items(), key=lambda kv: SCALE[kv[0]]['order'])),
        'collections': collections,
    }
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    # The ids the frozen-flag reader should walk (every art collection).
    (out_path.parent / 'frozen-read-list.json').write_text(json.dumps([c['id'] for c in art]) + '\n', encoding='utf-8')

    print(f'wrote {out_path} ({out_path.stat().st_size // 1024} KB), {len(collections)} collections')
    for k, n in out['counts'].items():
        print(f'  {SCALE[k]["label"]:<44} {n:>4}')
    print(f"  hand-checked: {sum(c['evidence_level'] == 'hand_checked' for c in collections.values())}, "
          f"with a helper hint: {sum(bool(c['helper']) for c in collections.values())}, frozen flag read: {sum(c['owner']['frozen_state'] is not None for c in collections.values())}")
    print('checks passed: ' + '; '.join(f'{k}={v[0]}' for k, v in expect.items()))


if __name__ == '__main__':
    main()
