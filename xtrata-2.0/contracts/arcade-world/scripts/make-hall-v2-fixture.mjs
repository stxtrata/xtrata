#!/usr/bin/env node
// Writes recursive-apps/xtrata-arcade/tests/fixtures/hall-v2-demo.json: the exact read-only results (Clarity hex) the hall's v2 reader gets
// from a simnet registry seeded with the four-doorways demo, at three moments. The hall's tests replay them (no chain needed), and
// tests/hall-v2-seed.test.mjs checks the checked-in file still matches what the contract and the toolkit produce.
//   node scripts/make-hall-v2-fixture.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cvToHex, hexToCV } from '@stacks/transactions';
import { boot } from '../tests/helpers.mjs';
import { argCv } from '../ops/lib/steps.mjs';
import * as V2 from '../ops/lib/v2.mjs';
import { loadReader, readHall } from '../ops/lib/hallread.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const FIXTURE = join(root, '..', '..', 'recursive-apps', 'xtrata-arcade', 'tests', 'fixtures', 'hall-v2-demo.json');
const CONTRACT = 'xtrata-world-v2';

export async function buildFixture() {
  const demo = JSON.parse(readFileSync(join(root, 'ops', 'examples', 'four-doorways-testnet-hall.scene.json'), 'utf8'));
  const { simnet, deployer, W } = await boot();
  const who = (v) => ({ deployer, publisher: W[0] }[v] || v);
  const run = (plan) => plan.steps.forEach((s) => {
    const r = simnet.callPublicFn(CONTRACT, s.fn, s.args.map((a) => argCv(a, who)), who(s.as));
    if (r.result.type !== 'ok') throw new Error(`${s.fn}: ${JSON.stringify(r.result)}`);
  });
  const { codec } = loadReader();
  // blobs: each distinct result once; a scenario's calls map "fn|args" to a blob index
  const out = { note: 'generated by contracts/arcade-world/scripts/make-hall-v2-fixture.mjs; do not edit', registry: `${deployer}.${CONTRACT}`, blobs: [], scenarios: {} };
  const blob = (hex) => { let i = out.blobs.indexOf(hex); if (i < 0) i = out.blobs.push(hex) - 1; return i; };
  async function snap(name) {
    const calls = {};
    const read = async (id, fn, args) => {
      const hex = cvToHex(simnet.callReadOnlyFn(CONTRACT, fn, (args || []).map((a) => hexToCV(a)), deployer).result);
      calls[fn + '|' + (args || []).join(',')] = blob(hex);
      return codec.decodeCV(hex);
    };
    const expect = await readHall({ read, registry: out.registry });
    out.scenarios[name] = { burnHeight: simnet.burnBlockHeight, calls, expect };
  }
  const seed = V2.planSeed([demo], { height: simnet.burnBlockHeight, ownerAddress: deployer });
  run(seed);
  await snap('pending');
  simnet.mineEmptyBurnBlocks(10);
  await snap('active');
  let m = seed.manifest;
  for (const p of [V2.planPatch(m, { object: 'hall/bay-1/sign', params: { text: 'NEW TEXT' }, height: simnet.burnBlockHeight })]) { run(p); m = p.manifest; }
  const add = V2.planAdd(m, { bay: 'hall/bay-3', kind: 'sign-board', params: { text: 'SECOND', tone: 'blue', y: 1.4 }, height: simnet.burnBlockHeight });
  run(add);
  await snap('updated');
  return out;
}

if (process.argv[1] && process.argv[1].endsWith('make-hall-v2-fixture.mjs')) {
  const f = await buildFixture();
  writeFileSync(FIXTURE, JSON.stringify(f) + '\n');
  console.log(`fixture -> ${FIXTURE} (${Object.entries(f.scenarios).map(([k, v]) => `${k}: ${Object.keys(v.calls).length} reads`).join(', ')})`);
}
