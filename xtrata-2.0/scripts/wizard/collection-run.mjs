const arg = (name, fallback = null) => {
  const index = process.argv.indexOf(`--${name}`);
  if (index === -1) return fallback;
  const value = process.argv[index + 1];
  return value && !value.startsWith('--') ? value : true;
};
const flag = (name) => arg(name) === true;
const text = (name, fallback = null) => (typeof arg(name) === 'string' ? arg(name) : fallback);
const csv = (value) =>
  value && typeof value === 'string' ? value.split(',').map((part) => part.trim()).filter(Boolean) : [];

const say = (line = '') => console.log(line);

/* ------------------------------------------------------------------ */
/* the fake chain, for --dry                                           */
/* ------------------------------------------------------------------ */

/**
 * The fake chain, the fake fetch and the wallet resolver are imported from
 * run-thread.mjs rather than re-implemented. They already answer every read
 * this runner makes — quote, pause, chunk, creator, hash lookup, tip, balance,
 * nonces, transaction — and a second fake would be a second thing to drift away
 * from the real encoders.
 *
 * The journal is held in memory and never written. A dry run invents its
 * inscription ids and its transaction ids, and a file full of invented txids
 * sitting next to the real one is an accident waiting to happen.
 */
function dryPorts({ chain, wallets, wizard = 'builder', out = say }) {
  let journal = null;
  return {
    readJournal: () => journal,
    writeJournal: (path, value) => {
      journal = value;
    },
    fetchImpl: fakeFetch(chain),
    killSwitch: (env) => killSwitchEngaged(env),
    now: () => Date.UTC(2026, 6, 31, 12, 0, 0),
    sleep: async () => {},
    say: out,
    presentPlan: (plan, options) => out(formatCollectionPlan(plan, options)),
    // `out` rather than `say` throughout, so a caller that wants the real
    // fetch, submit and journal ports without the terminal can have them. The
    // ports a test cares about are the ones that could spend; the presenter is
    // not one of them and it prints a whole plan per mint.
    submit: async ({ plan, broadcast, wizardId, minerFeeUstx }) => {
      if (broadcast === true) {
        throw new WizardSafetyError('the dry submit port was asked to broadcast. It cannot, and it did not.');
      }
      const minted = chain.mint(plan.body, wallets[wizardId ?? wizard]?.address ?? null, minerFeeUstx);
      out(`    [dry] minted into the fake chain as #${minted.id}; nothing was signed and nothing was sent`);
      return { txid: minted.txid };
    }
  };
}

/**
 * The fake market for `--list --dry`, imported whole from market-run.mjs.
 *
 * The tokens being listed have to exist and have to be owned by the seller, so
 * they are minted into the fake market first and the seller is funded. That is
 * setup for a rehearsal and not a claim about the real chain: `--list --dry`
 * proves the sweep's shape, its prices and its refusals, and proves nothing at
 * all about whether those inscriptions are really there.
 */
function listingDryPorts({ art, ids, wallets, minerFeeUstx, out = say }) {
  const chain = makeFakeMarket({ tip: 8_700_000, minerFeeUstx });
  const address = wallets[art.wizard]?.address ?? null;
  for (const id of Object.values(ids)) chain.mint(id, address);
  if (address) chain.fund(address, 50_000_000n);
  const ports = marketDryPorts({ chain, sponsor: null, minerFeeUstx });

  // One journal per run id, in memory, never written. The market runner's own
  // dry ports keep a single journal because a market run is one run; a listing
  // sweep is nine of them, each with its own id, and a shared slot makes run
  // two load run one's record and halt on the mismatch. Keyed by path, which is
  // exactly what a real journal is keyed by.
  const journals = new Map();
  return {
    chain,
    ports: {
      ...ports,
      readJournal: (path) => journals.get(path) ?? null,
      writeJournal: (path, value) => journals.set(path, value),
      say: out,
      presentPlan: () => {}
    }
  };
}

