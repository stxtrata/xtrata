/** The concept and the plates, with no chain and no journal involved at all. */
function preview({ art, collectionId }) {
  say('');
  say(art.concept);
  say('');
  for (const line of art.describeLines()) say(line);
  say('');
  say(
    `asking ${groupDigits(art.price.pieceUstx)} microSTX a plate and ${groupDigits(art.price.manifestUstx)} for ` +
      `the list. ${art.pricing.reasoning}`
  );
  say('');
  say('=== PREVIEW: the manifest below lists SYNTHETIC ids. Nothing here is on chain. ===');
  say('');
  say(
    art.composeManifest({
      collectionId,
      members: art.pieces.map((piece) => ({ index: piece.index, id: String(9000 + piece.index) }))
    })
  );
  say('=== PREVIEW END. No key was read, no transaction was built, nothing was sent. ===');
}

/**
 * `--list`: which ids, from where.
 *
 * `--ids` and `--manifest-id` win, because an operator naming an id is making a
 * deliberate statement. Failing that the mint journal is read, which is the
 * only other place that knows what this collection actually minted.
 */
function listingIdsFor({ art, ids, manifestId, journal }) {
  const fromJournal = idsFromMintJournal(journal);
  const resolved = { ...fromJournal };
  for (const [index, id] of ids.entries()) resolved[String(index + 1)] = id;
  if (manifestId) resolved[MANIFEST_KEY] = manifestId;
  // Never list a key the collection does not have. A stray --ids entry past the
  // end would otherwise become a listing of somebody else's token at this
  // collection's price.
  const keys = new Set([...art.pieces.map((piece) => String(piece.index)), MANIFEST_KEY]);
  return Object.fromEntries(Object.entries(resolved).filter(([key]) => keys.has(key)));
}

async function main() {
  if (flag('help')) {
    usage();
    return 0;
  }
  if (flag('collections')) {
    say('');
    for (const line of describeCollections()) say(line);
    say('');
    say('Same eight subjects in all three: chunk, fold, seal, dependency edge, nonce, miner fee,');
    say('post-condition, escrow. Different readings, different pictures, different prices.');
    return 0;
  }

  loadWizardEnv();
  const env = process.env;
  const hiroUrl = text('hiro', DEFAULT_HIRO_URL);
  const collectionId = text('collection', DEFAULT_COLLECTION_ID);
  const art = getCollection(collectionId);
  const wizard = art.wizard;

  if (flag('preview')) {
    preview({ art, collectionId: art.id });
    return 0;
  }

  if (typeof arg('write') === 'string') {
    const dir = arg('write');
    mkdirSync(dir, { recursive: true });
    for (const piece of art.pieces) {
      const file = join(dir, `${String(piece.index).padStart(2, '0')}-${piece.id}.svg`);
      writeFileSync(file, art.renderPiece(piece.index), 'utf8');
      say(`  wrote ${file}`);
    }
    say('');
    say('Nothing was signed and nothing was sent. These are the exact bytes a mint would carry.');
    return 0;
  }

  const broadcast = flag('broadcast');
  const ids = csv(arg('ids'));

  if (arg('status')) {
    const report = await collectionStatusReport({
      ports: { ...journalPorts(), fetchImpl: globalThis.fetch },
      options: {
        collectionId: art.id,
        hiroUrl,
        knownIds: Object.fromEntries(ids.map((id, index) => [String(index + 1), id]))
      }
    });
    say(formatCollectionStatusTable(report));
    return 0;
  }

  const minerFeeUstx = BigInt(arg('max-tx-fee-ustx', String(DEFAULT_MAX_TX_FEE_USTX)));

  /* ---------------------------------------------------------------- */
  /* --list                                                            */
  /* ---------------------------------------------------------------- */

  if (flag('list')) {
    const wallets = walletsFor({ env, broadcast });
    const marketKey = text('market', DEFAULT_LISTING_MARKET);
    const journalIo = journalPorts();
    const mintJournalPath = join(
      new URL('.', import.meta.url).pathname,
      `.collection-${art.id}${broadcast ? '' : '.dry'}.json`
    );
    const listingIds = listingIdsFor({
      art,
      ids,
      manifestId: text('manifest-id', null),
      journal: broadcast ? journalIo.readJournal(mintJournalPath) : null
    });

    const plan = collectionListingPlan({
      collectionId: art.id,
      ids: listingIds,
      market: marketKey,
      feeBudgetUstx: BigInt(arg('fee-budget-ustx', String(MIN_FEE_BUDGET_USTX)))
    });
    say('');
    say(formatCollectionListingPlan(plan, { broadcast }));

    if (plan.listable.length === 0) {
      say('');
      say('Nothing to list. Mint the collection first, or pass --ids and --manifest-id.');
      return 1;
    }

    let ports;
    if (broadcast) {
      ports = {
        ...marketJournalPorts(),
        fetchImpl: globalThis.fetch,
        killSwitch: (killEnv) => killSwitchEngaged(killEnv),
        now: () => Date.now(),
        sleep: (ms) => new Promise((resolve) => setTimeout(resolve, ms)),
        say,
        presentPlan: () => {},
        submit: marketLiveSubmit({ hiroUrl }),
        sponsor: null
      };
      say('');
      say('=== BROADCAST. Every listing below is a real mainnet transaction and cannot be undone. ===');
    } else {
      // Dry: the ids being listed are served from a fake market that has been
      // told they exist. That is rehearsal scaffolding and it is said out loud
      // rather than left for someone to infer from a green table.
      ports = listingDryPorts({ art, ids: listingIds, wallets, minerFeeUstx }).ports;
      say('');
      say('=== DRY RUN. A fake market in this process. No key is read, nothing is signed, nothing is sent. ===');
      say('    the inscriptions below are minted into the fake market first, so the sweep has something to list.');
    }

    const result = await listCollection({
      ports,
      options: {
        collectionId: art.id,
        ids: listingIds,
        market: marketKey,
        broadcast,
        only: csv(arg('only')).length > 0 ? csv(arg('only')) : null,
        env,
        wallets,
        hiroUrl,
        feeBudgetUstx: BigInt(arg('fee-budget-ustx', String(MIN_FEE_BUDGET_USTX))),
        runSpendCapUstx: BigInt(arg('listing-cap-ustx', String(DEFAULT_LISTING_RUN_SPEND_CAP_USTX))),
        balanceFloorUstx: BigInt(arg('balance-floor-ustx', String(DEFAULT_BALANCE_FLOOR_USTX))),
        minerFeeUstx,
        confirmTimeoutMs: arg('confirm-timeout-minutes')
          ? Number(arg('confirm-timeout-minutes')) * 60_000
          : DEFAULT_CONFIRM_TIMEOUT_MS,
        confirmPollMs: arg('poll-seconds') ? Number(arg('poll-seconds')) * 1_000 : DEFAULT_CONFIRM_POLL_MS
      }
    });
    say(formatCollectionListingReport(result));
    return result.ok ? 0 : 1;
  }

  /* ---------------------------------------------------------------- */
  /* the mint                                                          */
  /* ---------------------------------------------------------------- */

  const piece = arg('piece') ? Number(arg('piece')) : null;
  const from = piece ?? Number(arg('from', 1));
  const to = piece ?? Number(arg('to', art.length));

  const options = {
    collectionId: art.id,
    from,
    to,
    broadcast,
    manifest: !flag('no-manifest'),
    hiroUrl,
    env,
    runSpendCapUstx: BigInt(arg('run-spend-cap-ustx', String(DEFAULT_RUN_SPEND_CAP_USTX))),
    spendCapUstx: BigInt(arg('spend-cap-ustx', String(DEFAULT_SPEND_CAP_USTX))),
    balanceFloorUstx: BigInt(arg('balance-floor-ustx', String(DEFAULT_BALANCE_FLOOR_USTX))),
    minerFeeUstx,
    confirmTimeoutMs: arg('confirm-timeout-minutes')
      ? Number(arg('confirm-timeout-minutes')) * 60_000
      : DEFAULT_CONFIRM_TIMEOUT_MS,
    confirmPollMs: arg('poll-seconds') ? Number(arg('poll-seconds')) * 1_000 : DEFAULT_CONFIRM_POLL_MS,
    mempoolWaitMs: arg('mempool-wait-minutes')
      ? Number(arg('mempool-wait-minutes')) * 60_000
      : DEFAULT_MEMPOOL_WAIT_MS,
    mempoolPollMs: arg('mempool-poll-seconds')
      ? Number(arg('mempool-poll-seconds')) * 1_000
      : DEFAULT_MEMPOOL_POLL_MS
  };

  const wallets = walletsFor({ env, broadcast });
  options.wallets = wallets;
  let ports;

  if (broadcast) {
    options.knownIds = Object.fromEntries(ids.map((id, index) => [String(index + 1), id]));
    ports = {
      ...journalPorts(),
      fetchImpl: globalThis.fetch,
      killSwitch: (killEnv) => killSwitchEngaged(killEnv),
      now: () => Date.now(),
      sleep: (ms) => new Promise((resolve) => setTimeout(resolve, ms)),
      say,
      presentPlan: (plan, presentOptions) => say(formatCollectionPlan(plan, presentOptions)),
      submit: liveSubmit({ hiroUrl })
    };
    say('');
    say(`=== BROADCAST. Every mint below is a real mainnet transaction and cannot be undone. (${art.title}) ===`);
  } else {
    // Pieces already minted have to exist for the manifest to list them, so a
    // dry run serves them from a fake chain. Real ids when --ids supplies them,
    // synthetic ones otherwise, said out loud either way.
    const chain = makeFakeChain({ tip: 8_700_000, feeUstx: 11_000n });
    const priorIds = Array.from(
      { length: Math.max(0, Math.min(from, art.length) - 1) },
      (_, index) => ids[index] ?? String(9001 + index)
    );
    options.knownIds = Object.fromEntries(priorIds.map((id, index) => [String(index + 1), id]));
    for (const [index, id] of priorIds.entries()) {
      chain.add(id, art.renderPiece(index + 1), wallets[wizard]?.address ?? null);
    }

    ports = dryPorts({ chain, wallets, wizard });
    say('');
    say(`=== DRY RUN (${art.title}). A fake chain in this process. No key is read, nothing is signed, nothing is sent. ===`);
    if (priorIds.length > 0) {
      const synthetic = priorIds.filter((id, index) => ids[index] === undefined);
      say(
        `    pieces 1..${from - 1} are served from locally generated plates at ${priorIds.map((id) => `#${id}`).join(', ')}` +
          (synthetic.length > 0
            ? `. ${synthetic.map((id) => `#${id}`).join(', ')} ${synthetic.length === 1 ? 'is' : 'are'} SYNTHETIC — ` +
              'pass --ids to rehearse against the real ones.'
            : '.')
      );
    }
    say('');
  }

  const result = await runCollection({ ports, options });
  say(formatCollectionRunReport(result));

  if (!result.ok) return 1;
  if (!broadcast) {
    say('');
    say('To do this for real, re-run with --broadcast and the real ids:');
    say(
      `  node scripts/wizard/collection-run.mjs --collection ${art.id} --from ${from} --to ${to}` +
        `${ids.length ? ` --ids ${ids.join(',')}` : ''} --broadcast`
    );
    say('');
    say(`Then list it: node scripts/wizard/collection-run.mjs --collection ${art.id} --list --broadcast`);
  }
  return 0;
}

const isDirectRun = Boolean(process.argv[1]) && pathToFileURL(process.argv[1]).href === import.meta.url;
if (isDirectRun) {
  main()
    .then((code) => {
      process.exitCode = code ?? 0;
    })
    .catch((error) => {
      console.error(`\n${error?.name === 'WizardSafetyError' || error?.name === 'WizardComposeError' ? error.message : error}`);
      process.exitCode = 1;
    });
}

export { COLLECTION_IDS, dryPorts, listingDryPorts, listingIdsFor, preview };
