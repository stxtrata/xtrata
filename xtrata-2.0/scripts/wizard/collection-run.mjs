#!/usr/bin/env node
/**
 * collection-run.mjs — mint and list a wizard's pixel-art collection.
 *
 * DRY RUN BY DEFAULT. With no flags it runs the whole loop against a fake
 * chain: no key is read, nothing is signed, nothing is sent, and no request
 * leaves this process. `--broadcast` is the only thing that spends.
 *
 * There are three collections, one per wizard, all drawing the same eight parts
 * of the mint path through that wizard's fixed concern:
 *
 *   c-machinery-001  The Machinery        Wizard-3, the Builder
 *   c-keeping-001    The Cost of Keeping  Wizard-1, the Archivist
 *   c-omission-001   What the Hash Omits  Wizard-2, the Skeptic
 *
 * `--collection <id>` picks one; the Builder's is the default, so every command
 * that worked when there was one collection still does the same thing. The
 * wizard is not a flag: a collection is minted and listed by the wizard that
 * conceived it, out of that wizard's wallet, or not at all.
 *
 * See the plan and the sizes without touching anything at all:
 *   node scripts/wizard/collection-run.mjs --preview
 *   node scripts/wizard/collection-run.mjs --collections
 *
 * Rehearse the whole mint against a fake chain:
 *   node scripts/wizard/collection-run.mjs --all --dry
 *   node scripts/wizard/collection-run.mjs --collection c-keeping-001 --all --dry
 *
 * Write the plates out to look at them:
 *   node scripts/wizard/collection-run.mjs --write /tmp/machinery
 *
 * What is confirmed, pending or missing, with every on-chain plate compared to
 * its generated bytes:
 *   node scripts/wizard/collection-run.mjs --status
 *
 * List what has been minted, at that wizard's own price:
 *   node scripts/wizard/collection-run.mjs --collection c-keeping-001 --list --dry
 *
 * Really do it (real mainnet transactions, real STX, irreversible):
 *   node scripts/wizard/collection-run.mjs --all --broadcast
 *
 * Every rail inscribe.mjs applies to one mint applies to each mint here, plus
 * the run journal, the nonce asymmetry, the run-level spend cap and the kill
 * switch, all imported from run-thread-core.mjs rather than restated. The one
 * rail with no corpus equivalent is the member check: the manifest refuses to
 * name an id whose chunk u0 is not byte-identical to the plate it claims to be.
 * The listing path imports market-run-core.mjs whole for the same reason.
 *
 * There is no `--resolve` here, and that is not an omission. A corpus entry
 * quotes the block it was written at, so a lost transaction id can never
 * afterwards be matched by content hash and only a human can close it. A plate
 * names no block and no fee, so its hash never changes and `--status` can
 * settle the same question definitively at any point in the future.
 *
 * See scripts/wizard/README.md.
 */

