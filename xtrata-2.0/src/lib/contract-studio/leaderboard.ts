const buildGeneratedTest = (configuration: LeaderboardConfiguration) => `import { Cl } from '@stacks/transactions';
import { describe, expect, it } from 'vitest';

const accounts = simnet.getAccounts();
const deployer = accounts.get('deployer')!;
const wallet1 = accounts.get('wallet_1')!;
const wallet2 = accounts.get('wallet_2')!;
const contract = \`\${deployer}.xtrata-studio-leaderboard\`;

describe('generated Xtrata leaderboard', () => {
  it('rejects scores until the pinned asset has been verified', () => {
    expect(simnet.callPublicFn(contract, 'submit-score',
      [Cl.uint(100), Cl.stringAscii('ACE')], wallet1).result).toBeErr(Cl.uint(101));
  });
  it('verifies the pinned remote asset and covers score failure paths', () => {
    expect(simnet.callPublicFn(contract, 'verify-asset', [], wallet1).result).toBeOk(Cl.bool(true));
    expect(simnet.callPublicFn(contract, 'submit-score',
      [Cl.uint(${configuration.minScore}), Cl.stringAscii('ACE')], wallet1).result).toBeOk(Cl.uint(1));
    expect(simnet.callPublicFn(contract, 'submit-score',
      [Cl.uint(${configuration.minScore}), Cl.stringAscii('ACE')], wallet1).result).toBeErr(Cl.uint(105));
    expect(simnet.callPublicFn(contract, 'submit-score',
      [Cl.uint(${BigInt(configuration.maxScore) + 1n}), Cl.stringAscii('MAX')], wallet2).result).toBeErr(Cl.uint(103));
  });
  it('tests reset permission', () => {
    expect(simnet.callPublicFn(contract, 'start-next-season', [], wallet1).result).toBeErr(Cl.uint(${configuration.seasons ? '100' : '109'}));
    ${configuration.seasons ? `expect(simnet.callPublicFn(contract, 'start-next-season', [], deployer).result).toBeOk(Cl.uint(2));` : ''}
  });
});
`;

