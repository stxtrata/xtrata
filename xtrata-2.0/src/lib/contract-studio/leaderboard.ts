export const generateLeaderboardProject = async (
  asset: XtrataAssetRef,
  configuration: LeaderboardConfiguration
): Promise<StudioProject> => {
  const source = generateLeaderboardSource(asset, configuration);
  const configurationHash = await sha256Hex(canonicalJson(configuration));
  const sourceHash = await sha256Hex(source);
  const manifest = {
    manifestVersion: '1',
    projectName: configuration.projectName,
    network: asset.network,
    xtrataAssets: [asset],
    template: LEADERBOARD_TEMPLATE,
    modules: ['xtrata-asset-ref/1', 'leaderboard-core/1', 'submission-policy/1', 'season-reset/1', 'events/1'],
    configuration,
    roles: { deployer: '', administrator: configuration.administrator, treasury: '' },
    upgradeModel: 'immutable',
    generatedArtifacts: { contractSourceHash: sourceHash, configurationHash },
    deployment: { contractPrincipal: '', transactionId: '', blockHeight: null },
    customised: false
  };
  const artifacts: StudioArtifact[] = [
    { path: 'Clarinet.toml', content: buildClarinetToml(asset) },
    { path: 'package.json', content: packageJson },
    { path: 'vitest.config.ts', content: vitestConfig },
    { path: 'contracts/xtrata-studio-leaderboard.clar', content: source },
    {
      path: 'tests/xtrata-studio-leaderboard.test.ts',
      content: buildGeneratedTest(configuration)
    },
    { path: 'xtrata-project.json', content: canonicalJson(manifest) },
    {
      path: 'README.md',
      content: `# ${configuration.projectName}\n\nGenerated from ${LEADERBOARD_TEMPLATE.id}/${LEADERBOARD_TEMPLATE.version}.\n\nRun \`npm install\` and \`npm test\` after adding the pinned Xtrata core or faithful mock to the Clarinet project. Deploy with a matching-network wallet only.\n`
    },
    {
      path: 'SECURITY.md',
      content: `# Security report\n\nRisk: Tier 1 (no asset transfers).\n\nPinned dependency: ${asset.coreContractId}#${asset.tokenId} / ${asset.contentHash}.\n\nPrivileged role: ${configuration.administrator} may ${configuration.seasons ? 'start seasons' : 'not reset the permanent season'}${configuration.submissionPolicy === 'administrator' ? ' and submit scores' : ''}.\n\nTrust assumptions: public scores are wallet-authenticated, not proof that a game result was honestly earned. The template is tested, not audited.\n`
    },
    {
      path: 'src/client.ts',
      content: `import { PostConditionMode, stringAsciiCV, uintCV } from '@stacks/transactions';
export const buildSubmitScore = (score: bigint, alias: string) => ({
  functionName: 'submit-score',
  functionArgs: [uintCV(score), stringAsciiCV(alias)],
  postConditionMode: PostConditionMode.Deny,
  postConditions: []
});
export const READ_ONLY_FUNCTIONS = ['get-asset-reference', 'get-current-season', 'get-player-score', 'get-leaderboard-entry', 'get-configuration'] as const;
`
    },
    {
      path: 'contract-interface.json',
      content: canonicalJson({
        public: [
          { name: 'verify-asset', args: [] },
          { name: 'submit-score', args: ['uint', 'string-ascii 12'] },
          { name: 'start-next-season', args: [] }
        ],
        readOnly: [
          'get-asset-reference',
          'get-current-season',
          'get-player-score',
          'get-leaderboard-entry',
          'get-configuration'
        ]
      })
    }
  ];
  return { source, sourceHash, configurationHash, manifest, artifacts };
};
