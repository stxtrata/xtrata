// Publishes the FLAC sample packs to the Audionaut web app (the "web samples").
//
//   node audionaut-library/tools/build-web-packs.mjs
//
// Copies packs/<id>.audpack into public/audionaut/daw/media/packs/ and the FLAC decoder
// into public/audionaut/daw/js/codecs/, and writes the generated catalogue
// public/audionaut/daw/js/pack-catalogue.js (pack list, container hashes, one compact row per
// sound). The browser verifies each downloaded pack against the container sha256 recorded
// here, then each sound against the pack's own index. Re-run after any pack changes.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";
import { readAudpack } from "./audpack-reader.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const lib = path.resolve(here, "..");
const root = path.resolve(lib, "..");
const daw = path.join(root, "public/audionaut/daw");
const outPacks = path.join(daw, "media/packs");
const outCodecs = path.join(daw, "js/codecs");
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");

// Display order: core CC0 first, then attribution, then the unverified tier last.
const TIER_ORDER = { core: 0, attribution: 1, unverified: 2 };
const TIER_LABEL = { core: "CC0", attribution: "CC-BY", unverified: "unverified licence" };

fs.mkdirSync(outPacks, { recursive: true });
fs.mkdirSync(outCodecs, { recursive: true });
for (const f of fs.readdirSync(outPacks))
  if (f.endsWith(".audpack")) fs.rmSync(path.join(outPacks, f));

const credits = [];
const creditIx = new Map();
const creditId = (c) => {
  const k = c || "";
  if (!creditIx.has(k)) {
    creditIx.set(k, credits.length);
    credits.push(k);
  }
  return creditIx.get(k);
};

const licences = [];
const licenceIx = new Map();
const licenceId = (l) => {
  const k = l || "";
  if (!licenceIx.has(k)) {
    licenceIx.set(k, licences.length);
    licences.push(k);
  }
  return licenceIx.get(k);
};

const packs = [];
for (const file of fs.readdirSync(path.join(lib, "packs")).filter((f) => f.endsWith(".audpack")).sort()) {
  const id = file.slice(0, -8);
  const bytes = fs.readFileSync(path.join(lib, "packs", file));
  const man = JSON.parse(fs.readFileSync(path.join(lib, "packs", `${id}.manifest.json`), "utf8"));
  const digest = sha(bytes);
  if (digest !== man.container.sha256 || bytes.length !== man.container.bytes)
    throw new Error(`${id}: container does not match its manifest`);
  const { index } = await readAudpack(new Uint8Array(bytes.buffer, bytes.byteOffset, bytes.length));
  if (index.codec !== "flac" || index.sounds.length !== man.count)
    throw new Error(`${id}: unexpected codec or sound count`);
  fs.copyFileSync(path.join(lib, "packs", file), path.join(outPacks, file));
  const lic = index.license || {};
  const title = index.sounds[0].meta.label.split(" — ")[0];
  packs.push({
    id,
    title,
    tier: index.tier,
    spdx: lic.spdx,
    licence: lic.name,
    url: lic.url || null,
    attribution: lic.attributionRequired === true || index.tier === "attribution",
    notice: index.tier === "unverified" ? String(lic.text || "").split("\n\n").slice(0, 1).join("") : null,
    bytes: bytes.length,
    sha256: digest,
    credits: lic.credits || [],
    sounds: index.sounds.map((s) => {
      const m = s.meta;
      return [
        s.id, // assetId = "<soundId>@<root>@<layer>"
        m.label,
        m.rootMidi ?? null,
        m.folder || "",
        Math.round((m.duration || 0) * 100) / 100,
        creditId(m.credit),
        s.samples,
        licenceId(m.license), // per-sound SPDX: a pack can mix CC-BY 3.0 and 4.0
      ];
    }),
  });
}
packs.sort((a, b) => TIER_ORDER[a.tier] - TIER_ORDER[b.tier] || a.title.localeCompare(b.title));

const total = packs.reduce((n, p) => n + p.sounds.length, 0);
const header = `// GENERATED by audionaut-library/tools/build-web-packs.mjs. Do not edit by hand.
// ${packs.length} FLAC sample packs (audpack/1), ${total} sounds. Nothing here is inscribed yet:
// the packs are served as static files from media/packs/ until they are.
//
// PACKS[i] = { id, title, tier, spdx, licence, url, attribution, notice, bytes, sha256, credits, sounds }
// sounds[i] = [assetId, label, rootMidi|null, folder, durationSec, creditIndex, samples, licenceIndex]
`;
const body = `export const TIER_LABEL = ${JSON.stringify(TIER_LABEL)};
export const PACK_CREDITS = ${JSON.stringify(credits)};
export const PACK_LICENCES = ${JSON.stringify(licences)};
export const PACKS = ${JSON.stringify(packs)};
`;
fs.writeFileSync(path.join(daw, "js/pack-catalogue.js"), header + body);

// Fallback decoder for browsers whose decodeAudioData lacks FLAC (pure JS, no WebAssembly).
const codec = fs.readFileSync(path.join(lib, "codecs/codec-flac.mjs"));
fs.writeFileSync(path.join(outCodecs, "codec-flac.mjs"), codec);
const cm = JSON.parse(fs.readFileSync(path.join(lib, "codecs/codec-flac.extension.json"), "utf8"));
if (sha(codec) !== cm.module.sha256) throw new Error("codec-flac.mjs does not match its manifest");

console.log(`${packs.length} packs, ${total} sounds, ${(packs.reduce((n, p) => n + p.bytes, 0) / 1048576).toFixed(1)} MB`);
for (const p of packs) console.log(p.id.padEnd(12), p.tier.padEnd(12), String(p.sounds.length).padStart(4), p.title);
